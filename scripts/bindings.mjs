// Generates the desktop app's TypeScript types from the Rust types in nvoke-core (ts-rs, behind the `ts`
// feature) into src/lib/migrate/bindings, so the web view and the core can't drift apart.
//
//   node scripts/bindings.mjs           regenerate the files
//   node scripts/bindings.mjs --check   fail if the files on disk differ from what the Rust types generate
import { execFileSync } from "node:child_process";
import { existsSync, mkdirSync, mkdtempSync, readdirSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const target = join(root, "src", "lib", "migrate", "bindings");
const check = process.argv.includes("--check");

function generate(into) {
  mkdirSync(into, { recursive: true });
  execFileSync("cargo", ["test", "--features", "ts", "export_bindings"], {
    cwd: join(root, "crates", "core"),
    env: { ...process.env, TS_RS_EXPORT_DIR: into },
    stdio: ["ignore", "ignore", "inherit"],
  });
  const files = readdirSync(into).filter((f) => f.endsWith(".ts") && f !== "index.ts").sort();
  if (files.length === 0) throw new Error("No bindings were generated; is a type missing #[ts(export)]?");
  const index = ["// Generated by scripts/bindings.mjs. Do not edit.", ...files.map((f) => `export type * from "./${f.replace(/\.ts$/, "")}";`)].join("\n") + "\n";
  writeFileSync(join(into, "index.ts"), index);
  return files.concat("index.ts").sort();
}

function read(dir) {
  return Object.fromEntries(readdirSync(dir).filter((f) => f.endsWith(".ts")).map((f) => [f, readFileSync(join(dir, f), "utf8")]));
}

if (check) {
  const scratch = mkdtempSync(join(tmpdir(), "nvoke-bindings-"));
  try {
    generate(scratch);
    const fresh = read(scratch);
    const onDisk = existsSync(target) ? read(target) : {};
    const problems = [];
    for (const name of new Set([...Object.keys(fresh), ...Object.keys(onDisk)])) {
      if (!(name in onDisk)) problems.push(`missing: ${name}`);
      else if (!(name in fresh)) problems.push(`no longer generated: ${name}`);
      else if (fresh[name] !== onDisk[name]) problems.push(`out of date: ${name}`);
    }
    if (problems.length) {
      console.error(`src/lib/migrate/bindings is stale:\n  ${problems.join("\n  ")}\nRun: npm run bindings`);
      process.exit(1);
    }
    console.log("bindings are up to date");
  } finally {
    rmSync(scratch, { recursive: true, force: true });
  }
} else {
  // Regenerate from scratch so a removed type's file goes away too.
  if (existsSync(target)) rmSync(target, { recursive: true, force: true });
  const files = generate(target);
  console.log(`wrote ${files.length} files to src/lib/migrate/bindings`);
}
